/// 规则式 AI 客服。基于关键词匹配返回答案。
/// 生产环境可替换为调用大模型 API（传入用户问题，返回流式回答）。
class AISupport {
  static String answer(String question) {
    final q = question.toLowerCase();
    if (_hit(q, ['积分', '点', '余额', 'balance'])) {
      return '积分可用于解锁联系方式、查看相册和学历证书（各 100 积分）。获取方式：① 看广告 +300 积分/个；② 限量充值（100 积分 = 0.01 元）。';
    }
    if (_hit(q, ['广告', 'ad', '激励', '视频'])) {
      return '在「积分」页面点击「看广告赚积分」，观看一个激励视频即可获得 300 积分。广告由合作广告平台提供。';
    }
    if (_hit(q, ['充值', 'recharge', '钱', '人民币', '元', '支付', '付款', '微信', '支付宝'])) {
      return '积分支持限量充值：100 积分 = 0.01 元，单账号累计充值上限为 ¥100。请在「积分」页选择充值档位（演示，未接真实支付）。';
    }
    if (_hit(q, ['联系方式', '电话', '微信', '解锁', '查看', 'contact'])) {
      return '查看对方联系方式需消耗 100 积分。点击详情页「查看联系方式」并确认解锁即可。';
    }
    if (_hit(q, ['照片', '相册', '相片', 'photo', '图片'])) {
      return '相册查看需 100 积分解锁；解锁后可见该用户全部照片。';
    }
    if (_hit(q, ['学历', '证书', 'edu', '文凭'])) {
      return '学历证书照片查看需 100 积分解锁，用于验证对方学历真实性。';
    }
    if (_hit(q, ['礼物', '礼品', 'gift', '兑换'])) {
      return '在「礼物」页面可用积分购买礼物赠送给心仪对象；礼物也可兑换回积分。';
    }
    if (_hit(q, ['定位', '地区', '区域', '城市', 'location', 'region', '国内', '全球', '范围'])) {
      return '定位默认覆盖国内主要城市；可在「我的 → 定位设置」切换为「全球」范围。匹配结果会按所选范围筛选。';
    }
    if (_hit(q, ['安全', '隐私', '文明', '规范', '辱骂', '不文明', '词'])) {
      return '我们内置不文明词库过滤，聊天与资料中的不文明用语会被拦截或打码，营造文明交友环境。';
    }
    if (_hit(q, ['匹配', '推荐', '怎么用', '功能', '使用'])) {
      return '在首页点击「AI 快速匹配」，系统会基于你的画像（年龄/学历/地域/爱好等）智能推荐对象。';
    }
    if (_hit(q, ['人工', '客服', '转', '投诉', '举报', '退款'])) {
      return '已为您记录，人工客服将在 1 个工作日内通过站内信联系您。当前为 AI 助手为您解答。';
    }
    if (_hit(q, ['你好', 'hi', 'hello', '在吗', '您好'])) {
      return '您好！我是 AI 客服助手，可解答积分、广告、充值、礼物、定位、隐私等问题，请问有什么可以帮您？';
    }
    return '感谢您的提问。我是 AI 客服助手，可解答积分/广告/充值/礼物/定位/隐私等相关问题。若以上未覆盖，可回复「人工」转接人工客服。';
  }

  static bool _hit(String q, List<String> keys) => keys.any((k) => q.contains(k));
}
